import { DataSource } from 'typeorm';
import { v4 as uuidv4 } from 'uuid';
import { AppDataSource } from '../config/database';
import { Order, OrderStatus, Product, Cart, CartItem, CartItemStatus, CartStatus, User } from '../entities';
import { StockReservationService } from './stockReservation.service';

export interface CheckoutInput {
  userId: string;
  cartId?: string;
  reservationId: string;
  idempotencyKey: string;
}

export interface CheckoutResult {
  success: boolean;
  order?: Order;
  isIdempotentReplay?: boolean;
  error?: string;
  statusCode?: number;
}

export class CheckoutService {
  private reservationService: StockReservationService;

  constructor(reservationService?: StockReservationService) {
    this.reservationService = reservationService || new StockReservationService();
  }

  /**
   * Processes checkout with atomic TypeORM transactions and idempotency protection.
   * 
   * How duplicate orders are prevented:
   * 1. Idempotency Key validation:
   *    Each checkout request requires a unique `idempotencyKey` generated by the client.
   *    If an order with this key already exists in the database, the existing order is returned
   *    immediately without reprocessing (safe replay).
   * 2. Database Unique Constraint:
   *    The `idempotencyKey` column on the `orders` table has a UNIQUE index at the DB level,
   *    meaning concurrent simultaneous submissions with the same key will cause the database
   *    to reject the second write with a unique constraint violation.
   * 3. Redis Single-Use Token:
   *    The reservation token is consumed upon successful order creation, preventing replay
   *    with alternate idempotency keys.
   */
  async processCheckout(input: CheckoutInput): Promise<CheckoutResult> {
    const { userId, cartId, reservationId, idempotencyKey } = input;

    if (!userId || !reservationId || !idempotencyKey) {
      return {
        success: false,
        error: 'Missing required checkout parameters: userId, reservationId, and idempotencyKey are mandatory.',
        statusCode: 400
      };
    }

    const orderRepository = AppDataSource.getRepository(Order);

    // 1. Check for existing order with the same Idempotency Key
    const existingOrder = await orderRepository.findOne({
      where: { idempotencyKey }
    });

    if (existingOrder) {
      return {
        success: true,
        order: existingOrder,
        isIdempotentReplay: true,
        statusCode: 200
      };
    }

    // 2. Validate Reservation in Redis
    const reservation = await this.reservationService.getReservation(reservationId);
    if (!reservation) {
      return {
        success: false,
        error: 'Reservation has expired or is invalid. Please reserve stock again.',
        statusCode: 410 // 410 Gone
      };
    }

    if (reservation.userId !== userId) {
      return {
        success: false,
        error: 'Unauthorized: Reservation does not belong to this user.',
        statusCode: 403
      };
    }

    const productId = reservation.productId || '';
    const quantity = parseInt(reservation.quantity || '1', 10);

    // 3. Execute Checkout inside an Atomic Database Transaction
    const queryRunner = AppDataSource.createQueryRunner();
    await queryRunner.connect();
    await queryRunner.startTransaction();

    try {
      const productRepo = queryRunner.manager.getRepository(Product);
      const product = await productRepo.findOne({ where: { id: productId } });

      if (!product) {
        throw new Error(`Product ${productId} not found in database.`);
      }

      // Check persistent stock availability
      if (product.availableStock < quantity) {
        throw new Error(`Database inventory out of sync: requested ${quantity}, available ${product.availableStock}.`);
      }

      // Decrement persistent stock
      product.availableStock -= quantity;
      await productRepo.save(product);

      // Ensure user exists in DB for Order relation
      const userRepo = queryRunner.manager.getRepository(User);
      let user = await userRepo.findOne({ where: { id: userId } });
      if (!user) {
        user = userRepo.create({
          id: userId,
          email: `${userId}@flashkart.com`,
          name: 'Flash Sale Shopper'
        });
        await userRepo.save(user);
      }

      const newOrder = queryRunner.manager.create(Order, {
        orderNumber,
        userId,
        cartId: cartId || null,
        idempotencyKey,
        totalAmount,
        status: OrderStatus.CONFIRMED,
        orderItemsSnapshot: [
          {
            productId: product.id,
            productTitle: product.title,
            quantity,
            unitPrice,
            subtotal: totalAmount
          }
        ]
      });

      const savedOrder = await queryRunner.manager.save(Order, newOrder);

      // Update Cart & CartItem if cartId was provided
      if (cartId) {
        const cartItemRepo = queryRunner.manager.getRepository(CartItem);
        const cartItem = await cartItemRepo.findOne({
          where: { cartId, productId }
        });

        if (cartItem) {
          cartItem.status = CartItemStatus.PURCHASED;
          await cartItemRepo.save(cartItem);
        }

        const cartRepo = queryRunner.manager.getRepository(Cart);
        const cart = await cartRepo.findOne({ where: { id: cartId } });
        if (cart) {
          cart.status = CartStatus.CHECKED_OUT;
          await cartRepo.save(cart);
        }
      }

      // Commit the database transaction
      await queryRunner.commitTransaction();

      // 4. Cleanup Redis reservation token so it cannot be used again
      // Notice: we do NOT restore stock to Redis, because the purchase completed!
      const redis = (this.reservationService as any).redis;
      if (redis) {
        await redis.del(
          `flash:res:${reservationId}`,
          `flash:user_res:${userId}:${productId}`
        );
      }

      return {
        success: true,
        order: savedOrder,
        isIdempotentReplay: false,
        statusCode: 201
      };
    } catch (err: any) {
      // Rollback database changes on failure
      await queryRunner.rollbackTransaction();

      console.error('[CheckoutService] Checkout transaction failed. Rolling back DB and restoring Redis reservation.', err);

      // Release reservation in Redis so stock is returned to the pool
      await this.reservationService.releaseReservation(
        productId,
        reservationId,
        quantity,
        userId
      );

      return {
        success: false,
        error: err.message || 'Checkout transaction failed. Reservation has been released.',
        statusCode: 500
      };
    } finally {
      await queryRunner.release();
    }
  }
}
